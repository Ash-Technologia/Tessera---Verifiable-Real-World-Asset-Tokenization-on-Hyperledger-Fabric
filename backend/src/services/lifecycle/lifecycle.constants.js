'use strict';

/**
 * TESSERA Asset Lifecycle Constants — Phase 7A
 *
 * Defines the canonical vocabulary and rules for real-world asset lifecycle state machine:
 *
 *   DRAFT
 *     ↓
 *   REGISTERED
 *     ↓
 *   UNDER_VERIFICATION ──→ REJECTED (terminal)
 *     ↓
 *   VERIFIED ──────────┬──→ RESTRICTED ──→ VERIFIED / TOKENIZED / RETIRED
 *     ↓ (tokenize)     ├──→ PLEDGED    ──→ VERIFIED / TOKENIZED / RETIRED
 *   TOKENIZED          ├──→ REDEEMED   ──→ RETIRED
 *     ├──→ RESTRICTED  └──→ RETIRED (terminal)
 *     ├──→ PLEDGED
 *     ├──→ REDEEMED
 *     └──→ RETIRED
 */

const LIFECYCLE_STATES = Object.freeze({
  DRAFT: 'DRAFT',
  REGISTERED: 'REGISTERED',
  UNDER_VERIFICATION: 'UNDER_VERIFICATION',
  VERIFIED: 'VERIFIED',
  REJECTED: 'REJECTED',
  TOKENIZED: 'TOKENIZED',
  RESTRICTED: 'RESTRICTED',
  PLEDGED: 'PLEDGED',
  REDEEMED: 'REDEEMED',
  RETIRED: 'RETIRED',
});

const TERMINAL_STATES = Object.freeze([
  LIFECYCLE_STATES.REJECTED,
  LIFECYCLE_STATES.RETIRED,
]);

/**
 * Deterministic transition map.
 * Any state transition not explicitly allowed here MUST be rejected.
 */
const ALLOWED_TRANSITIONS = Object.freeze({
  [LIFECYCLE_STATES.DRAFT]: Object.freeze([
    LIFECYCLE_STATES.REGISTERED,
  ]),

  [LIFECYCLE_STATES.REGISTERED]: Object.freeze([
    LIFECYCLE_STATES.UNDER_VERIFICATION,
  ]),

  [LIFECYCLE_STATES.UNDER_VERIFICATION]: Object.freeze([
    LIFECYCLE_STATES.VERIFIED,
    LIFECYCLE_STATES.REJECTED,
  ]),

  [LIFECYCLE_STATES.VERIFIED]: Object.freeze([
    LIFECYCLE_STATES.TOKENIZED,
    LIFECYCLE_STATES.RESTRICTED,
    LIFECYCLE_STATES.PLEDGED,
    LIFECYCLE_STATES.REDEEMED,
    LIFECYCLE_STATES.RETIRED,
  ]),

  [LIFECYCLE_STATES.TOKENIZED]: Object.freeze([
    LIFECYCLE_STATES.RESTRICTED,
    LIFECYCLE_STATES.PLEDGED,
    LIFECYCLE_STATES.REDEEMED,
    LIFECYCLE_STATES.RETIRED,
  ]),

  [LIFECYCLE_STATES.PLEDGED]: Object.freeze([
    LIFECYCLE_STATES.TOKENIZED,
    LIFECYCLE_STATES.VERIFIED,
    LIFECYCLE_STATES.RESTRICTED,
    LIFECYCLE_STATES.RETIRED,
  ]),

  [LIFECYCLE_STATES.RESTRICTED]: Object.freeze([
    LIFECYCLE_STATES.TOKENIZED,
    LIFECYCLE_STATES.VERIFIED,
    LIFECYCLE_STATES.PLEDGED,
    LIFECYCLE_STATES.RETIRED,
  ]),

  [LIFECYCLE_STATES.REDEEMED]: Object.freeze([
    LIFECYCLE_STATES.RETIRED,
  ]),

  [LIFECYCLE_STATES.REJECTED]: Object.freeze([]), // Terminal
  [LIFECYCLE_STATES.RETIRED]: Object.freeze([]),  // Terminal
});

const LIFECYCLE_ERROR_CODES = Object.freeze({
  INVALID_LIFECYCLE_TRANSITION: 'INVALID_LIFECYCLE_TRANSITION',
  EMPTY_TRANSITION_REASON: 'EMPTY_TRANSITION_REASON',
  MISSING_ACTOR: 'MISSING_ACTOR',
  UNKNOWN_LIFECYCLE_STATE: 'UNKNOWN_LIFECYCLE_STATE',
  SAME_STATE_TRANSITION: 'SAME_STATE_TRANSITION',
  TERMINAL_STATE: 'TERMINAL_STATE',
  ASSET_NOT_FOUND: 'ASSET_NOT_FOUND',
});

module.exports = {
  LIFECYCLE_STATES,
  TERMINAL_STATES,
  ALLOWED_TRANSITIONS,
  LIFECYCLE_ERROR_CODES,
};
